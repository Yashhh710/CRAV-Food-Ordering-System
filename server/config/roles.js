function hasPermission(userOrRole, requiredPermission) {
  if (!userOrRole) return false;
  const role = typeof userOrRole === 'string' ? userOrRole : userOrRole.role;
  if (!role) return false;
  const roleKey = role.toUpperCase();
  if (roleKey === ROLES.SUPER_ADMIN) return true;
  const rolePerms = ROLE_PERMISSIONS[roleKey] || [];
  if (rolePerms.includes('*')) return true;
  if (rolePerms.includes(requiredPermission)) return true;
  if (typeof userOrRole === 'object' && Array.isArray(userOrRole.permissions)) {
    if (userOrRole.permissions.includes('*') || userOrRole.permissions.includes(requiredPermission)) {
      return true;
    }
  }
  return false;
}

